// Writes ../seed.sql from src/api/mock-data.ts, so the database and mock mode hold the same rows.
// Run with `bun run seed`, then recreate the database container.

import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { mockData } from '../src/api/mock-data.ts'
import type { EntityPath } from '../src/api/types.ts'

// Insert order respects foreign keys.
const TABLES: [EntityPath, string][] = [
  ['categories', 'categories'],
  ['circuits', 'circuits'],
  ['drivers', 'drivers'],
  ['races', 'races'],
  ['teams', 'teams'],
  ['engines', 'engines'],
  ['chassis', 'chassis'],
  ['cars', 'cars'],
  ['articles', 'articles'],
  ['article-texts', 'article_texts'],
]

/** DATE columns: the mock holds the JSON the Go back end returns for them (midnight UTC timestamps). */
const DATE_COLUMNS = new Set(['race_date'])

const quote = (s: string) => `'${s.replaceAll("'", "''")}'`

function literal(column: string, value: unknown): string {
  if (value == null) return 'NULL'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (typeof value === 'object') return `${quote(JSON.stringify(value))}::jsonb`
  const s = String(value)
  return quote(DATE_COLUMNS.has(column) ? s.slice(0, 10) : s)
}

const out = ['-- GENERATED by front-end/scripts/gen-seed.ts from front-end/src/api/mock-data.ts. Do not edit by hand.', '']

for (const [path, table] of TABLES) {
  const rows = mockData[path] as unknown as Record<string, unknown>[]
  const columns = Object.keys(rows[0])
  out.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES`)
  out.push(rows.map((row) => `  (${columns.map((c) => literal(c, row[c])).join(', ')})`).join(',\n') + ';', '')
}

const target = resolve(import.meta.dirname, '../../seed.sql')
writeFileSync(target, out.join('\n'))
console.log(`wrote ${target}`)
